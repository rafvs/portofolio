/**
 * Komponen TechStack — Menampilkan 3 card kategori stack + marquee berjalan.
 */
const TechStack = ({ className = '' }) => {
  const { t } = useTranslation()

  // 📥 MENGAMBIL DATA DARI DATABASE SUPABASE:
  // Memanggil custom hook useSupabaseContent untuk mengambil data teknologi & tools dari tabel 'tech_stack'.
  const remoteStack = useSupabaseContent('tech_stack')

  const [revealRef, reveal] = useInView({ once: true, rootMargin: '-10% 0px -10% 0px' })

  const remoteGroups = ['languages', 'frameworks', 'tools'].map((id) => ({
    id,
    labelKey: `techStack.${id}`,
    labelFallback: id,
    items: remoteStack.filter((item) => item.category === id).map((item) => ({ name: item.name, icon: item.icon_name })),
  })).filter((group) => group.items.length)
  const stackGroups = remoteGroups.length ? remoteGroups : STACK_GROUPS
  const sourceMarquee = remoteStack.length ? remoteStack.map((item) => ({ name: item.name, icon: item.icon_name })) : MARQUEE_STACK
  const marqueeItems = [...sourceMarquee, ...sourceMarquee]

  return (
    <section className={`stack${className ? ` ${className}` : ''}`} id="stack">
      <div className="stack-inner section-shell">

        {/* HEADER SECTION */}
        <div className={`section-heading reveal${reveal ? ' is-visible' : ''}`} ref={revealRef}>
          <p className="section-kicker">{t('sections.techKicker')}</p>
          <div className="section-heading__copy">
            <BlurText
              text={t('sections.techTitle')}
              className="section-title"
              delay={60}
              animateBy="words"
              direction="bottom"
              threshold={0.2}
              rootMargin="-80px"
            />
            <p className="section-description">{t('sections.techDescription')}</p>
          </div>
        </div>

        {/* CARD GRID (3 kategori) */}
        <div className="stack-cards">
          {stackGroups.map((group, gIdx) => (
            <div className="stack-card" key={group.id}
              style={{ '--card-delay': `${gIdx * 0.1}s` }}>
              <p className="stack-card__label">
                {t(group.labelKey, { defaultValue: group.labelFallback })}
              </p>
              <ul className="stack-card__list">
                {group.items.map((item) => (
                  <li key={item.name} className="stack-card__item">
                    <span className="stack-card__icon" aria-hidden="true">
                      {icons[item.icon]}
                    </span>
                    <span className="stack-card__name">{item.name}</span>
                  </li>
                ))}
              </ul>
            </div>
          ))}
        </div>
      </div>

      {/* MARQUEE BAR (dengan icon) */}
      <div className="stack-marquee" aria-label={t('techStack.label', { defaultValue: 'Tech stack' })}>
        <div className="stack-marquee__track">
          {marqueeItems.map((item, index) => (
            <div className="stack-item" key={`${item.name}-${index}`}>
              <span className="stack-item__icon" aria-hidden="true">
                {icons[item.icon]}
              </span>
              <span>{item.name}</span>
              <i aria-hidden="true">/</i>
            </div>
          ))}
        </div>
      </div>
    </section>
  )
}

export default TechStack
